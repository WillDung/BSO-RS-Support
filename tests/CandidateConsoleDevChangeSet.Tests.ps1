#requires -Version 7.4
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$root = Split-Path -Parent $PSScriptRoot
$scriptPath = Join-Path $root 'scripts\New-BsoRsCandidateConsoleDevChangeSet.ps1'
$directory = Join-Path ([IO.Path]::GetTempPath()) "console-change-set-$([Guid]::NewGuid().ToString('N'))"
[IO.Directory]::CreateDirectory($directory) | Out-Null
$passed = 0
function Assert-Test([bool]$Condition, [string]$Name) {
    if (-not $Condition) { throw "FAIL: $Name" }
    $script:passed++
}
$names = @(
    'candidate-console.html', 'candidate-console-environment.js', 'candidate-console-policy.js',
    'candidate-console.js', 'candidate-console-availability.js'
)
$rows = @()
foreach ($name in $names) {
    $rows += @{
        name = "os_/bso/$name"; webresourceid = [Guid]::NewGuid().ToString('D'); ismanaged = $false
        content = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes("SYNTHETIC BASELINE $name"))
    }
}
$snapshot = @{
    solution = @{ uniquename = 'os_sr_bso_rs_support'; ismanaged = $false }
    current = $rows; published = $rows
}
$snapshotPath = Join-Path $directory 'snapshot.json'
$output = Join-Path $directory 'prepared'
$rejected = Join-Path $directory 'rejected'
$arguments = @{
    OrganizationUrl = 'https://dev.example.invalid'
    EnvironmentId = '11111111-1111-4111-8111-111111111111'
    OrganizationId = '22222222-2222-4222-8222-222222222222'
    BaselineSnapshotPath = $snapshotPath
    OutputDirectory = $output
}
try {
    $snapshot | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath $snapshotPath
    & $scriptPath @arguments | Out-Null
    $manifest = Get-Content -LiteralPath (Join-Path $output 'manifest.json') -Raw | ConvertFrom-Json
    Assert-Test (@($manifest.resources).Count -eq 5 -and @($manifest.resources | Where-Object name -Like '*.css').Count -eq 0) `
        'Prepare exactly the five approved resources without CSS'
    Assert-Test (-not $manifest.deploymentReady -and $manifest.scopeApprovalRequired -and
        $manifest.syntheticIsolation -ceq 'IMPLEMENTED_OFFLINE_REQUIRES_SERVER_DEPLOYMENT_AND_VERIFICATION' -and
        $manifest.publicationConcurrency -ceq 'REQUIRES_CONFIRMED_CHANGE_WINDOW_AND_FRESH_CONDITIONAL_WRITES') `
        'Preparation cannot grant isolation, scope approval or a publication freeze'
    foreach ($resource in $manifest.resources) {
        Assert-Test ((Get-FileHash -LiteralPath (Join-Path $output $resource.file) -Algorithm SHA256).Hash.ToLowerInvariant() -ceq
            $resource.expectedSha256) "Pin exact generated bytes: $($resource.file)"
    }
    $configuration = Get-Content -LiteralPath (Join-Path $output 'candidate-console-environment.js') -Raw
    $config = ([regex]::Match($configuration, 'const configuration = (\{.*\});').Groups[1].Value) | ConvertFrom-Json
    Assert-Test ($config.mode -ceq 'DEV' -and $config.syntheticDataOnly -and $config.candidateCoreEnabled -and
        -not $config.devDirectWriteFallbackEnabled -and $config.diagnosticsMode -ceq 'OFF' -and
        $config.organizationUrl -ceq $arguments.OrganizationUrl -and
        $config.environmentId -ceq $arguments.EnvironmentId -and $config.organizationId -ceq $arguments.OrganizationId -and
        $config.PSObject.Properties.Name -notcontains 'availabilityEnabled') 'Bind DEV without enabling fallback or Calendar'
    $configHash = ($manifest.resources | Where-Object file -CEQ 'candidate-console-environment.js').expectedSha256
    Assert-Test ((Get-Content -LiteralPath (Join-Path $output 'candidate-console.html') -Raw).Contains(
        "candidate-console-environment.js?v=$($configHash.Substring(0,12))")) 'Version the environment URL from generated bytes'
    [xml]$publish = (Get-Content -LiteralPath (Join-Path $output 'publish-request.json') -Raw | ConvertFrom-Json).ParameterXml
    Assert-Test (@($publish.importexportxml.webresources.webresource).Count -eq 5 -and
        @($publish.importexportxml.ChildNodes | Where-Object Name -NE 'webresources').Count -eq 0) 'Publish shape contains only five resource IDs'
    foreach ($name in 'candidate-console-policy.js','candidate-console.js','candidate-console-availability.js') {
        Assert-Test ((Get-FileHash -LiteralPath (Join-Path $output $name)).Hash -ceq
            (Get-FileHash -LiteralPath (Join-Path $root "solutions\CandidateConsole\WebResources\os_\bso\$name")).Hash) `
            "Preserve application source: $name"
    }
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $packagePath = Join-Path $directory 'synthetic-package.nupkg'
    $archive = [IO.Compression.ZipFile]::Open($packagePath, [IO.Compression.ZipArchiveMode]::Create)
    try {
        $entry = $archive.CreateEntry('lib/net462/os_sr_cact.dll')
        $writer = [IO.StreamWriter]::new($entry.Open())
        try { $writer.Write('SYNTHETIC MANIFEST FIXTURE ONLY - NOT A DEPLOYABLE ASSEMBLY') }
        finally { $writer.Dispose() }
    } finally { $archive.Dispose() }
    $deltaPath = Join-Path $output 'synthetic-isolation-manifest.json'
    $deltaScript = Join-Path $root 'scripts\New-BsoRsSyntheticIsolationManifest.ps1'
    $deltaArgs = @{
        PackagePath = $packagePath; ConsoleManifestPath = (Join-Path $output 'manifest.json'); OutputPath = $deltaPath
    }
    & $deltaScript @deltaArgs | Out-Null
    $delta = Get-Content -LiteralPath $deltaPath -Raw | ConvertFrom-Json
    Assert-Test (-not $delta.deploymentReady -and -not $delta.serverComponents.configuration.configurationPrepared -and
        $delta.serverComponents.requiredBaseSteps.Count -eq 59 -and $delta.webResources.Count -eq 5) `
        'Delta lists all 59 base guards and five resources without granting activation'
    Assert-Test ($delta.package.sha256 -ceq (Get-FileHash -LiteralPath $packagePath).Hash.ToLowerInvariant() -and
        $delta.sources.Count -eq 7 -and $delta.approvalBoundaries.Count -eq 5) `
        'Delta pins server/API sources and package bytes with separate approval boundaries'
    $deltaHash = (Get-FileHash -LiteralPath $deltaPath).Hash
    $deltaRejected = $false
    try { & $deltaScript @deltaArgs | Out-Null } catch {
        $deltaRejected = $_.Exception.Message -ceq 'ISOLATION_MANIFEST_OUTPUT_ALREADY_EXISTS'
    }
    Assert-Test ($deltaRejected -and (Get-FileHash -LiteralPath $deltaPath).Hash -ceq $deltaHash) `
        'Delta generation never overwrites reviewed historical evidence'
    $deltaArgs.OutputPath = Join-Path $output 'drift-delta.json'
    $resourcePath = Join-Path $output 'candidate-console-policy.js'
    $savedBytes = [IO.File]::ReadAllBytes($resourcePath)
    try {
        [IO.File]::AppendAllText($resourcePath, "`n// SYNTHETIC DRIFT FIXTURE")
        $deltaRejected = $false
        try { & $deltaScript @deltaArgs | Out-Null } catch {
            $deltaRejected = $_.Exception.Message -ceq 'ISOLATION_CONSOLE_SOURCE_DRIFT'
        }
        Assert-Test ($deltaRejected -and -not (Test-Path -LiteralPath $deltaArgs.OutputPath)) `
            'Delta rejects resource drift before producing evidence'
    } finally { [IO.File]::WriteAllBytes($resourcePath, $savedBytes) }
    $rejectedExisting = $false
    try { & $scriptPath @arguments | Out-Null } catch { $rejectedExisting = $_.Exception.Message -ceq 'DEV_CHANGE_SET_OUTPUT_ALREADY_EXISTS' }
    Assert-Test $rejectedExisting 'Never overwrite an existing prepared change set'
    $arguments.OutputDirectory = $rejected
    $snapshot.current = @($rows | ForEach-Object { $_.Clone() })
    $snapshot.current[0].content = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes('NEWER UNPUBLISHED EDIT'))
    $snapshot | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath $snapshotPath
    $driftRejected = $false
    try { & $scriptPath @arguments | Out-Null } catch {
        $driftRejected = $_.Exception.Message -ceq 'DEV_CHANGE_SET_PENDING_DRAFT_REQUIRES_RECONCILIATION'
    }
    Assert-Test ($driftRejected -and -not (Test-Path -LiteralPath $rejected)) 'Reject conflicting draft before generating files'
    $source = Get-Content -LiteralPath $scriptPath -Raw
    Assert-Test ($source -notmatch '\bInvoke-(WebRequest|RestMethod)\b' -and $source -notmatch '\bpac\s+' -and
        $source -notmatch 'Start-Process|launchPersistentContext') 'Offline preparation cannot send requests or launch a browser'
    Assert-Test (($manifest.requiredSequence -join "`n") -match 'fresh exact If-Match, never wildcard' -and
        ($manifest.requiredSequence -join "`n") -match 'stop on 412' -and
        ($manifest.requiredSequence -join "`n") -match 'Reconfirm the window' -and
        ($manifest.requiredSequence -join "`n") -match 'Do not retry ambiguous') `
        'Conditional updates do not replace the publication window or authorize retries'
    $tokens = $null
    $parseErrors = $null
    $deploymentAst = [Management.Automation.Language.Parser]::ParseFile(
        (Join-Path $root 'scripts\Deploy-BsoRsCandidateConsole.ps1'), [ref]$tokens, [ref]$parseErrors)
    if ($parseErrors.Count) { throw 'Deployment helper parse failed' }
    $requestFunction = $deploymentAst.Find({
        param($node)
        $node -is [Management.Automation.Language.FunctionDefinitionAst] -and
            $node.Name -eq 'Invoke-DataverseRequest'
    }, $true)
    . ([ScriptBlock]::Create($requestFunction.Extent.Text))
    $target = @{ OrganizationUrl = 'https://dev.example.invalid'; SolutionUniqueName = 'os_sr_bso_rs_support' }
    $script:ApiRoot = 'https://dev.example.invalid/api/data/v9.2/'
    $script:AccessToken = 'SYNTHETIC_OFFLINE_NOT_A_CREDENTIAL'
    $script:Counts = @{ PATCH = 0; GET = 0; POST = 0 }
    $script:mockCalls = @()
    $script:mockAmbiguous = $false
    function Invoke-WebRequest {
        param($Uri, $Method, $Headers, $MaximumRetryCount, $MaximumRedirection, $TimeoutSec,
            [switch]$SkipHttpErrorCheck, $Body, $ContentType)
        $script:mockCalls += @{ Method = $Method; Headers = $Headers; Retries = $MaximumRetryCount }
        if ($script:mockAmbiguous) { throw [IO.IOException]::new('Synthetic lost response') }
        return @{ StatusCode = if ($Headers['If-Match'] -ceq 'W/"current"') { 204 } else { 412 } }
    }
    $path = "webresourceset($($rows[0].webresourceid))"
    $stale = Invoke-DataverseRequest -Method PATCH -Path $path -ETag 'W/"stale"' -Body @{ content = 'U1lOVEhFVElD' }
    Assert-Test ($stale.StatusCode -eq 412 -and $script:mockCalls.Count -eq 1 -and
        $script:mockCalls[0].Headers['If-Match'] -ceq 'W/"stale"' -and $script:mockCalls[0].Retries -eq 0) `
        'Fixture stale ETag returns 412 with one exact conditional PATCH and zero retries'
    $script:mockAmbiguous = $true
    $ambiguousStopped = $false
    try { Invoke-DataverseRequest -Method PATCH -Path $path -ETag 'W/"current"' -Body @{ content = 'U1lOVEhFVElD' } }
    catch { $ambiguousStopped = $_.Exception.Message -ceq 'Candidate Console write outcome is uncertain; stop without retry.' }
    Assert-Test ($ambiguousStopped -and $script:mockCalls.Count -eq 2 -and $script:Counts.POST -eq 0) `
        'Fixture ambiguous write stops without replay or publication; no tenant call occurs'
    Write-Output "Candidate Console DEV change-set checks passed: $passed"
} finally {
    Remove-Item -LiteralPath $directory -Recurse -Force
}
